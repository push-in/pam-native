    /**
     * The non-null fields as wire properties (enums as their values, grid
     * templates as their wire form), in KEYS order. A Style is immutable,
     * so the result is computed once per instance.
     *
     * @return array<int, float|int|bool|string>
     */
    public function properties(): array
    {
        // Android/iOS hosts read the fields natively (same result).
        static $native = null;
        $native ??= function_exists('pam_native_style_properties');
        if ($native) {
            return pam_native_style_properties($this, self::KEYS);
        }
        $properties = [];
        foreach (self::KEYS as $field => $key) {
            $value = $this->$field;
            if ($value === null) {
                continue;
            }
            if ($value instanceof \BackedEnum) {
                $value = $value->value;
            } elseif ($value instanceof GridTemplate) {
                $value = $value->toWire();
            }
            $properties[$key] = $value;
        }

        return $properties;
    }

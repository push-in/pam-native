    /**
     * Search key: canonical decomposition with combining marks
     * (U+0300–U+036F) removed, then lower case. "Ação" and "acao" fold to
     * the same key, like JavaScript's normalize('NFD') + /\p{M}/ removal.
     */
    public static function fold(string $value, bool $lowercase = true): string
    {
        if ($value === '') {
            return '';
        }
        $folded = (string) preg_replace('/[\x{0300}-\x{036F}]/u', '', strtr($value, self::BASE));

        return $lowercase ? mb_strtolower($folded, 'UTF-8') : $folded;
    }

    /**
     * Folds $value and returns, for every folded character, the index of the
     * original character it came from, so matches found in the folded text
     * can be highlighted in the original.
     *
     * @return array{0: string, 1: list<int>}
     */
    public static function foldWithMap(string $value): array
    {
        $folded = '';
        $map = [];
        foreach (mb_str_split($value, 1, 'UTF-8') as $index => $character) {
            $piece = self::fold($character);
            foreach ($piece === '' ? [] : mb_str_split($piece, 1, 'UTF-8') as $foldedCharacter) {
                $folded .= $foldedCharacter;
                $map[] = $index;
            }
        }

        return [$folded, $map];
    }

    /** Accent- and case-insensitive substring test. */
    public static function contains(string $haystack, string $needle): bool
    {
        $needle = self::fold(trim($needle));

        return $needle === '' || str_contains(self::fold($haystack), $needle);
    }

    /** Number of user-perceived characters (code points) in $value. */
    public static function length(string $value): int
    {
        return count(mb_str_split($value, 1, 'UTF-8'));
    }
